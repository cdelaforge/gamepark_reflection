import { css } from '@emotion/react'

/**
 * The digits of a clue, drawn like a seven-segment display: one svg per digit, as high as the clue tile
 */
export function ClueNumber({ value }: { value: number }) {
  return (
    <div css={containerCss}>
      {Array.from(String(value), Number).map((digit, index) => (
        <svg key={index} viewBox={`0 0 ${widths[digit]} 200`} css={digitCss}>
          {digits[digit].map(points => (
            <polygon key={points} points={points} fill={color} stroke={color} strokeWidth={1} />
          ))}
        </svg>
      ))}
    </div>
  )
}

